import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { createHarness, pickPort, repoRoot, startDaemon, startWebhookSink, stopDaemon, waitForHealth } from './_lib.mjs';

const ui = path.join(repoRoot, 'apps/desktop-ui');
const { chromium } = createRequire(path.join(ui, 'package.json'))('playwright');
const output = path.resolve(process.env.RELEASE_GATE_OUTPUT_DIR || path.join(repoRoot, 'output/playwright'));
await fs.mkdir(output, { recursive: true });
const dir = await fs.mkdtemp(path.join(output, 'channel-accounts-'));
const harness = await createHarness('channel-accounts');
const viewport = { width: 1280, height: 900 };
const steps = [];
let context, browser, page, video, daemon, receiver, desktop;
try {
  daemon = startDaemon({ workspace: harness.workspace, settingsPath: harness.settingsPath, port: await pickPort() });
  await waitForHealth(daemon.baseUrl, daemon.proc);
  receiver = await startWebhookSink();
  const port = await pickPort();
  desktop = { proc: spawn(process.execPath, [path.join(repoRoot, 'scripts/static-server.mjs'), path.join(ui, 'ui'), String(port)], { stdio: ['ignore', 'pipe', 'inherit'] }) };
  await once(desktop.proc.stdout, 'data');
  browser = await chromium.launch({ channel: process.env.RELEASE_GATE_BROWSER_CHANNEL || undefined });
  context = await browser.newContext({ viewport, recordVideo: { dir, size: viewport }, reducedMotion: 'reduce', locale: 'pt-BR' });
  page = await context.newPage();
  video = page.video();
  page.setDefaultTimeout(12_000);
  await page.addInitScript(url => { window.__MLX_PILOT_DAEMON_URL__ = url; }, daemon.baseUrl);
  await page.goto(`http://127.0.0.1:${port}`);
  const $ = id => page.locator('#' + id);
  const form = async (id, enabled) => {
    await page.waitForTimeout(550);
    const response = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/channels/upsert-account'));
    await $('agent-channel-save-btn').click();
    const payload = await (await response).json();
    assert.equal(payload.accounts.find(account => account.account_id === id)?.enabled, enabled);
    await $('agent-channel-form-feedback').getByText(`Conta mattermost:${id} salva.`).waitFor();
  };
  const edit = name => page.locator(`[data-channel-action="edit"][data-account="${name}"]`).click();
  const send = async expected => {
    const response = page.waitForResponse(r => r.url().endsWith('/agent/message/send'));
    await $('agent-send-test-btn').click();
    const received = await response;
    assert.equal(received.status(), expected);
    return received.json();
  };
  await page.locator('[data-panel="agent"]').click();
  await page.locator('[data-agent-view="config"]').click();
  await page.locator('[data-config-section="integrations"]').click();
  await $('agent-channel-select').selectOption('mattermost');
  await $('agent-channel-account-id').fill('aula');
  await $('agent-channel-credentials').fill(receiver.baseUrl + '/webhook');
  await $('agent-channel-set-default').check();
  await form('aula', true);
  assert.equal(await $('agent-channel-credentials').inputValue(), '');
  steps.push('create_default_account');
  await page.waitForTimeout(800);
  await edit('aula');
  await $('agent-channel-enabled').uncheck();
  await form('aula', false);
  await page.getByText('Testar conexão e envio', { exact: true }).click();
  await $('agent-send-channel').selectOption('mattermost');
  await $('agent-send-account').selectOption('aula');
  await $('agent-send-target').fill('turma');
  await $('agent-send-message').fill('Teste de entrega da aula');
  assert.equal((await send(403)).error_code, 'permission_error');
  assert.equal(receiver.requests.length, 0);
  steps.push('edit_without_reentering_credentials', 'disabled_delivery_blocked');
  await page.waitForTimeout(1000);
  await edit('aula');
  await $('agent-channel-enabled').check();
  await form('aula', true);
  await page.locator('[data-channel-action="rename"][data-account="aula"]').click();
  await $('agent-channel-dialog-value').fill('semestre');
  await $('agent-channel-dialog-confirm').click();
  await page.locator('[data-channel-action="edit"][data-account="semestre"]').waitFor();
  await $('agent-send-channel').selectOption('mattermost');
  await $('agent-send-account').selectOption('semestre');
  const delivered = await send(200);
  assert.equal(delivered.account_id, 'semestre');
  assert.equal(receiver.requests.length, 1);
  assert.match(JSON.stringify(receiver.requests[0].body), /Teste de entrega da aula/);
  await $('agent-channel-action-feedback').filter({ hasText: delivered.message_id }).waitFor();
  steps.push('rename_default_account', 'enabled_delivery_received_once');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(dir, 'channel-accounts.png') });
  console.log('Validated channel accounts:', dir);
} catch (error) {
  process.exitCode = 1;
  steps.push({ failure: error.message });
  console.error(error);
} finally {
  await context?.close();
  if (video) await video.saveAs(path.join(dir, 'channel-accounts.webm'));
  if (video) await video.delete();
  await browser?.close();
  await receiver?.close();
  await stopDaemon(desktop);
  await stopDaemon(daemon);
  await fs.writeFile(path.join(dir, 'report.json'), JSON.stringify({ steps, receiverRequests: receiver?.requests.length }, null, 2));
}
